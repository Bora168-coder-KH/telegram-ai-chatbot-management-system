MOCK_FAQS = {"en": MOCK_FAQS_EN, "km": MOCK_FAQS_KM}


async def seed_mock_faqs(session: AsyncSession) -> int:
    """Insert every mock FAQ whose question is not in the database yet. Returns the count added."""
    existing = set((await session.execute(select(FAQ.question))).scalars())
    added = 0
    for language, categories in MOCK_FAQS.items():
        for category, items in categories.items():
            for question, answer, keywords in items:
                if question in existing:
                    continue
                session.add(FAQ(question=question, answer=answer, category=category,
                                keywords=keywords, language=language))
                added += 1
    await session.commit()
    return added


async def main() -> None:
    await init_db()
    async with SessionLocal() as session:
        added = await seed_mock_faqs(session)
    print(f"Added {added} mock FAQs.")


if __name__ == "__main__":
    asyncio.run(main())
